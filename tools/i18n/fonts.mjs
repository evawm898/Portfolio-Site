#!/usr/bin/env node
// tools/i18n/fonts.mjs — the self-hosted, subset fonts of a translated page.
//
// Google Fonts is unreliable in mainland China, so a translated page loads none of it: every face
// it uses is a file in assets/fonts/<locale>/, cut down to the characters that locale's pages
// actually use. The CJK faces are megabytes whole and a few hundred KB cut; that cut is the point.
//
//   node tools/i18n/fonts.mjs --build                 every published locale -> assets/fonts/<locale>/
//   node tools/i18n/fonts.mjs --check                 fail if a published locale uses a character
//                                                     its committed fonts do not hold
//   node tools/i18n/fonts.mjs --sample <text> <dir>   cut the fonts for the characters of a text
//                                                     file into <dir> (sizing; writes nothing else)
//
// Sources are npm packages pinned by version AND integrity in i18n/config.json; they are packed
// into a gitignored cache and never committed. --build needs python3 with fonttools and brotli
// (pip install fonttools brotli); --check needs neither.
//
// WHICH characters: every character of the locale's strings (i18n/<locale>/*.json) and of its
// generated pages. A CJK face gets the ones from U+2E80 up plus general and CJK punctuation; a
// Latin face gets Basic Latin, Latin-1 and whatever else below U+2E80 the pages use. A character
// a face has no glyph for is simply not in its file, and the next family in the stack draws it.
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const CONFIG = JSON.parse(readFileSync(join(ROOT, 'i18n/config.json'), 'utf8'));
const F = CONFIG.fonts, args = process.argv.slice(2), has = f => args.includes(f);

const ALWAYS_CJK = '，。、；：？！“”‘’（）《》〈〉【】「」—…·％℃～　';
const isCjk = c => { const p = c.codePointAt(0); return p >= 0x2E80 || (p >= 0x2000 && p <= 0x206F); };
function charsOf(text) {
  const all = new Set([...text].filter(c => c.codePointAt(0) > 0x20));
  const cjk = new Set([...ALWAYS_CJK, ...[...all].filter(isCjk)]);
  const latin = new Set([...all].filter(c => c.codePointAt(0) < 0x2E80));
  for (let p = 0x20; p <= 0x7E; p++) latin.add(String.fromCodePoint(p));
  for (let p = 0xA0; p <= 0xFF; p++) latin.add(String.fromCodePoint(p));
  return { cjk: [...cjk].sort().join(''), latin: [...latin].sort().join('') };
}
function localeText(locale, L) {
  let text = L.label;
  const dir = join(ROOT, 'i18n', locale);
  for (const f of existsSync(dir) ? readdirSync(dir) : []) for (const v of Object.values(JSON.parse(readFileSync(join(dir, f), 'utf8')).strings)) text += v[locale] || '';
  for (const p of CONFIG.pages) { const f = join(ROOT, L.dir, p.src); if (existsSync(f)) text += readFileSync(f, 'utf8').replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>|<[^>]+>/g, ' '); }
  return text;
}
function source(s) {                                        // the unpacked npm package, from the cache
  const cache = join(ROOT, F.cache), dir = join(cache, s.id);
  if (existsSync(join(dir, 'package'))) return join(dir, 'package');
  mkdirSync(dir, { recursive: true });
  console.log(`fetching ${s.pkg} ...`);
  const tgz = join(dir, execFileSync('npm', ['pack', '--silent', s.pkg], { cwd: dir, encoding: 'utf8' }).trim().split('\n').pop());
  const got = 'sha512-' + createHash('sha512').update(readFileSync(tgz)).digest('base64');
  if (got !== s.integrity) throw new Error(`${s.pkg}: integrity ${got} is not the pinned ${s.integrity}`);
  execFileSync('tar', ['xzf', tgz, '-C', dir, ...s.files.map(f => `package/${f.path}`)]);
  return join(dir, 'package');
}
function cut(outDir, sets, urlBase = '') {
  mkdirSync(outDir, { recursive: true });
  let css = '/* GENERATED by tools/i18n/fonts.mjs — do not edit. */\n', total = 0;
  const rows = [];
  for (const s of F.sources) {
    const pkg = source(s), txt = join(outDir, `.${s.set}.txt`);
    writeFileSync(txt, sets[s.set]);
    for (const f of s.files) {
      const name = `${s.id}-${f.weight.replace(' ', '-')}.woff2`, out = join(outDir, name);
      execFileSync('python3', ['-m', 'fontTools.subset', join(pkg, f.path), `--text-file=${txt}`, '--flavor=woff2', `--output-file=${out}`, '--layout-features=*', '--no-hinting', '--desubroutinize'], { stdio: ['ignore', 'ignore', 'inherit'] });
      const kb = statSync(out).size / 1024; total += kb; rows.push([name, kb]);
      css += `@font-face { font-family: "${s.family}"; font-style: normal; font-weight: ${f.weight}; font-display: swap; src: url("${urlBase}${name}") format("woff2"); }\n`;
    }
    execFileSync('rm', ['-f', txt]);
  }
  writeFileSync(join(outDir, 'fonts.css'), css);
  writeFileSync(join(outDir, 'charset.txt'), `cjk ${sets.cjk}\nlatin ${sets.latin}\n`);
  for (const [n, kb] of rows) console.log(`  ${n.padEnd(34)} ${kb.toFixed(0).padStart(5)} KB`);
  console.log(`  ${'total'.padEnd(34)} ${total.toFixed(0).padStart(5)} KB   (${[...sets.cjk].length} CJK characters, ${[...sets.latin].length} Latin)`);
}

if (has('--sample')) {
  const [file, dir] = args.slice(args.indexOf('--sample') + 1);
  cut(resolve(dir), charsOf(readFileSync(resolve(file), 'utf8')));
} else if (has('--build') || has('--check')) {
  const bad = [];
  for (const [locale, L] of Object.entries(CONFIG.locales)) {
    if (!L.published) { console.log(`${locale}: not published — no fonts ${has('--build') ? 'written' : 'to check'}`); continue; }
    const sets = charsOf(localeText(locale, L)), dir = join(ROOT, CONFIG.fontsDir, locale);
    if (has('--build')) { console.log(`${locale}:`); cut(dir, sets); continue; }
    if (!existsSync(join(dir, 'charset.txt'))) { bad.push(`${locale}: no fonts built — run --build`); continue; }
    const have = Object.fromEntries(readFileSync(join(dir, 'charset.txt'), 'utf8').trim().split('\n').map(l => [l.slice(0, l.indexOf(' ')), new Set(l.slice(l.indexOf(' ') + 1))]));
    for (const set of ['cjk', 'latin']) { const miss = [...sets[set]].filter(c => !have[set]?.has(c)); if (miss.length) bad.push(`${locale}: ${miss.length} ${set} character(s) used on the pages are not in the fonts (${miss.slice(0, 20).join('')}) — run --build`); }
    for (const m of readFileSync(join(dir, 'fonts.css'), 'utf8').matchAll(/url\("([^"]+)"\)/g)) if (!existsSync(join(dir, m[1]))) bad.push(`${locale}: fonts.css names ${m[1]}, which is missing`);
  }
  if (bad.length) { console.error(bad.map(b => `FAIL ${b}`).join('\n')); process.exitCode = 1; } else if (has('--check')) console.log('i18n fonts: in sync');
} else console.log('usage: fonts.mjs --build | --check | --sample <text file> <out dir>');
